const propertyOrder = ["verdant-court", "palm-house", "terrace-house", "courtyard-villa"];

function getImages(property) {
    return [
        ...property.exterior.map((image) => ({ ...image, category: "exterior" })),
        ...property.interior.map((image) => ({ ...image, category: "interior" }))
    ];
}

function setupMenu() {
    const menuToggle = document.querySelector(".menu-toggle");
    const mobileMenu = document.querySelector(".mobile-menu");

    if (!menuToggle || !mobileMenu) return;

    const closeMenu = () => {
        menuToggle.classList.remove("active");
        menuToggle.setAttribute("aria-expanded", "false");
        mobileMenu.classList.remove("active");
        mobileMenu.setAttribute("aria-hidden", "true");
        document.body.classList.remove("menu-open");
    };

    menuToggle.addEventListener("click", () => {
        const isOpen = menuToggle.classList.toggle("active");
        menuToggle.setAttribute("aria-expanded", String(isOpen));
        mobileMenu.classList.toggle("active", isOpen);
        mobileMenu.setAttribute("aria-hidden", String(!isOpen));
        document.body.classList.toggle("menu-open", isOpen);
    });

    mobileMenu.querySelectorAll("a").forEach((link) => {
        link.addEventListener("click", closeMenu);
    });
}

function setupHomeCards() {
    document.querySelectorAll("[data-property-card]").forEach((card) => {
        const id = card.dataset.propertyCard;
        const property = properties[id];
        if (!property) return;

        const images = getImages(property);
        let activeIndex = 0;
        const image = card.querySelector(".tile-media img");
        const count = card.querySelector(".image-count");

        card.querySelector(".tile-kicker").textContent = property.type;
        card.querySelector("h3").textContent = property.title;
        card.querySelector(".tile-location").textContent = property.location;

        const render = () => {
            image.style.opacity = "0";
            window.setTimeout(() => {
                image.src = images[activeIndex].src;
                image.alt = images[activeIndex].alt;
                count.textContent = `${activeIndex + 1} / ${images.length}`;
                image.style.opacity = "1";
            }, 90);
        };

        card.querySelector(".previous").addEventListener("click", () => {
            activeIndex = (activeIndex - 1 + images.length) % images.length;
            render();
        });

        card.querySelector(".next").addEventListener("click", () => {
            activeIndex = (activeIndex + 1) % images.length;
            render();
        });

        render();
    });
}

function setupLookbooks() {
    document.querySelectorAll("[data-lookbook]").forEach((strip) => {
        const category = strip.dataset.lookbook;
        const items = propertyOrder.flatMap((id) => {
            const property = properties[id];
            return property[category].slice(0, 2).map((image) => ({
                ...image,
                title: property.title
            }));
        });

        strip.innerHTML = items.map((item) => `
            <figure class="lookbook-item">
                <img src="${item.src}" alt="${item.alt}" loading="lazy">
                <p>${item.title}</p>
            </figure>
        `).join("");
    });
}

function setupDetailPage() {
    const detailPage = document.querySelector("[data-property-detail]");
    if (!detailPage) return;

    const params = new URLSearchParams(window.location.search);
    const id = params.get("id") || propertyOrder[0];
    const property = properties[id] || properties[propertyOrder[0]];
    const title = document.getElementById("propertyTitle");
    const mainImage = document.getElementById("mainImage");
    const counter = document.getElementById("detailCounter");
    const thumbnailStrip = document.querySelector(".thumbnail-strip");
    const imageGrid = document.getElementById("detailImageGrid");
    const tabButtons = document.querySelectorAll("[data-gallery-filter]");
    let activeFilter = "all";
    let activeIndex = 0;

    document.title = `${property.title} | KumaonNest`;
    document.getElementById("propertyType").textContent = property.type;
    title.textContent = property.title;
    document.getElementById("propertyLocation").textContent = property.location;
    document.getElementById("propertyPrice").textContent = property.price;
    document.getElementById("bedrooms").textContent = property.bedrooms;
    document.getElementById("bathrooms").textContent = property.bathrooms;
    document.getElementById("area").textContent = property.area;
    document.getElementById("propertyDescription").textContent = property.description;
    document.getElementById("detailPropertyField").value = property.title;
    document.getElementById("contactHint").textContent = `We will include ${property.title} in your enquiry.`;

    document.getElementById("featuresList").innerHTML = property.features
        .map((feature) => `<li>${feature}</li>`)
        .join("");

    const allImages = getImages(property);

    const filteredImages = () => allImages.filter((image) => {
        return activeFilter === "all" || image.category === activeFilter;
    });

    const renderMainImage = () => {
        const images = filteredImages();
        const current = images[activeIndex] || images[0];
        mainImage.src = current.src;
        mainImage.alt = current.alt;
        counter.textContent = `${activeIndex + 1} / ${images.length}`;

        thumbnailStrip.querySelectorAll(".thumbnail").forEach((button, index) => {
            button.classList.toggle("active", index === activeIndex);
        });
    };

    const renderThumbnails = () => {
        const images = filteredImages();
        thumbnailStrip.innerHTML = images.map((image, index) => `
            <button class="thumbnail${index === activeIndex ? " active" : ""}" type="button" aria-label="Show image ${index + 1}">
                <img src="${image.src}" alt="${image.alt}" loading="lazy">
            </button>
        `).join("");

        thumbnailStrip.querySelectorAll(".thumbnail").forEach((button, index) => {
            button.addEventListener("click", () => {
                activeIndex = index;
                renderMainImage();
            });
        });
    };

    const renderImageGrid = () => {
        imageGrid.innerHTML = allImages.map((image) => `
            <figure>
                <img src="${image.src}" alt="${image.alt}" loading="lazy">
                <figcaption>${image.category} / ${property.title}</figcaption>
            </figure>
        `).join("");
    };

    const updateFilter = (filter) => {
        activeFilter = filter;
        activeIndex = 0;
        tabButtons.forEach((button) => {
            button.classList.toggle("active", button.dataset.galleryFilter === filter);
        });
        renderThumbnails();
        renderMainImage();
    };

    document.querySelector(".gallery-nav.previous").addEventListener("click", () => {
        const images = filteredImages();
        activeIndex = (activeIndex - 1 + images.length) % images.length;
        renderMainImage();
    });

    document.querySelector(".gallery-nav.next").addEventListener("click", () => {
        const images = filteredImages();
        activeIndex = (activeIndex + 1) % images.length;
        renderMainImage();
    });

    tabButtons.forEach((button) => {
        button.addEventListener("click", () => updateFilter(button.dataset.galleryFilter));
    });

    let startX = 0;
    mainImage.addEventListener("touchstart", (event) => {
        startX = event.changedTouches[0].clientX;
    }, { passive: true });

    mainImage.addEventListener("touchend", (event) => {
        const endX = event.changedTouches[0].clientX;
        const delta = endX - startX;
        if (Math.abs(delta) < 45) return;

        const images = filteredImages();
        activeIndex = delta < 0
            ? (activeIndex + 1) % images.length
            : (activeIndex - 1 + images.length) % images.length;
        renderMainImage();
    }, { passive: true });

    renderImageGrid();
    updateFilter("all");
}

function setupEnquiryForms() {
    document.querySelectorAll("[data-enquiry-form]").forEach((form) => {
        form.addEventListener("submit", (event) => {
            event.preventDefault();

            const data = new FormData(form);
            const name = data.get("name");
            const contact = data.get("contact");
            const property = data.get("property");
            const message = data.get("message");
            const subject = encodeURIComponent(`Property enquiry: ${property}`);
            const body = encodeURIComponent(`Name: ${name}\nContact: ${contact}\nProperty: ${property}\n\n${message}`);
            const status = form.querySelector(".form-status");

            status.textContent = "Opening your email app with the enquiry details.";
            window.location.href = `mailto:hello@example.com?subject=${subject}&body=${body}`;
        });
    });
}

